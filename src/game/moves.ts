export function lerpPose(a: Pose, b: Pose, t: number): Pose {
  const clampT = Math.max(0, Math.min(1, t));
  const lerp = (x: number, y: number) => x + (y - x) * clampT;
  return {
    hipOffsetY: lerp(a.hipOffsetY, b.hipOffsetY),
    hipOffsetX: lerp(a.hipOffsetX, b.hipOffsetX),
    torsoLean: lerp(a.torsoLean, b.torsoLean),
    headTilt: lerp(a.headTilt, b.headTilt),
    upperArmF: lerp(a.upperArmF, b.upperArmF),
    forearmF: lerp(a.forearmF, b.forearmF),
    upperArmB: lerp(a.upperArmB, b.upperArmB),
    forearmB: lerp(a.forearmB, b.forearmB),
    thighF: lerp(a.thighF, b.thighF),
    shinF: lerp(a.shinF, b.shinF),
    thighB: lerp(a.thighB, b.thighB),
    shinB: lerp(a.shinB, b.shinB),
    weaponRelAngle: lerp(a.weaponRelAngle, b.weaponRelAngle),
    offhandWeaponRelAngle: lerp(a.offhandWeaponRelAngle ?? 15, b.offhandWeaponRelAngle ?? 15),
  };
}

export function sampleKeyframes(keyframes: MoveDefinition['keyframes'], t: number): Pose {
  if (keyframes.length === 0) return NEUTRAL_POSES.IDLE;
  if (t <= keyframes[0].t) return keyframes[0].pose;
  for (let i = 0; i < keyframes.length - 1; i++) {
    const k1 = keyframes[i];
    const k2 = keyframes[i + 1];
    if (t >= k1.t && t <= k2.t) {
      const span = Math.max(0.0001, k2.t - k1.t);
      const localT = (t - k1.t) / span;
      // Smoothstep easing for natural martial-arts momentum
      const eased = localT * localT * (3 - 2 * localT);
      return lerpPose(k1.pose, k2.pose, eased);
    }
  }
  return keyframes[keyframes.length - 1].pose;
}

